using System.IO;
using System.Linq;
using System.Text;
using Runavelle.Core;

/// <summary>Generates Docs/Content_Catalog.md from the live ContentDatabase (counts are never hand-typed).</summary>
public static class Catalog
{
    public static void Write(string path)
    {
        var db = ContentDatabase.Create();
        var sb = new StringBuilder();
        sb.AppendLine("# Runavelle — Content Catalog (generated)");
        sb.AppendLine();
        sb.AppendLine("Generated by `dotnet run --project Tools/Sim -c Release -- catalog`. Do not edit by hand.");
        sb.AppendLine();
        var soldiers = db.Units.Values.Where(u => u.Role == UnitRole.Soldier).ToList();
        var enemies = db.Units.Values.Where(u => u.Role == UnitRole.Enemy && u.Behavior != EnemyBehavior.Boss).ToList();
        var bosses = db.Units.Values.Where(u => u.Behavior == EnemyBehavior.Boss).ToList();
        sb.AppendLine("| Content | Count |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| Elements | {Elements.All.Length} |");
        sb.AppendLine($"| Bespoke reactions (+ generic Resonance) | {ReactionTable.AllBespoke.Count} |");
        sb.AppendLine($"| Building families | {db.Buildings.Count} |");
        sb.AppendLine($"| Building levels/variants | {db.Levels.Count} |");
        sb.AppendLine($"| Soldier types | {soldiers.Count} (branches: {db.SoldierBranches.Count}) |");
        sb.AppendLine($"| Generals | {db.Generals.Count} (with 2 evolutions: {db.Generals.Values.Count(g => g.Evolutions.Length == 2)}) |");
        sb.AppendLine($"| Enemy types (non-boss) | {enemies.Count} |");
        sb.AppendLine($"| Bosses | {bosses.Count} |");
        sb.AppendLine($"| Factions | {enemies.Select(e => e.Faction).Distinct().Count()} |");
        sb.AppendLine($"| Maps | {db.Maps.Count} |");
        sb.AppendLine($"| Royal Decrees | {db.Decrees.Count} |");
        sb.AppendLine($"| Equipment (Weapon/Relic) | {db.Equipment.Values.Count(e => e.Slot == EquipmentSlot.Weapon)}/{db.Equipment.Values.Count(e => e.Slot == EquipmentSlot.Relic)} |");
        sb.AppendLine();
        sb.AppendLine("## Elements & reactions");
        foreach (var e in Elements.All) { var i = Elements.Info(e); sb.AppendLine($"- **{i.Name}** ({i.Key}) – {i.Status}: {i.StatusDescription}"); }
        sb.AppendLine();
        foreach (var r in ReactionTable.AllBespoke) sb.AppendLine($"- **{r.Name}** = {Elements.Name(r.A)} + {Elements.Name(r.B)}: {r.Description}");
        sb.AppendLine($"- **{ReactionTable.ResonanceDef.Name}** (all other pairs): {ReactionTable.ResonanceDef.Description}");
        sb.AppendLine();
        sb.AppendLine("## Building families (tier tree)");
        foreach (var id in db.BuildingOrder)
        {
            var b = db.Buildings[id];
            sb.AppendLine($"### {b.Name} (`{id}`, {Loc.Family(b.Family)})");
            sb.AppendLine(b.Description);
            sb.AppendLine();
            foreach (var l in db.Levels.Values.Where(l => db.LevelOwner[l.Id] == id).OrderBy(l => l.Tier).ThenBy(l => l.Id).Take(40))
                sb.AppendLine($"- T{l.Tier}{(l.Branch != "" ? l.Branch : "")} `{l.Id}` **{l.Name}** – {l.Cost} – {l.Description}");
            int n = db.Levels.Values.Count(l => db.LevelOwner[l.Id] == id);
            if (n > 40) sb.AppendLine($"- … {n - 40} more variants");
            sb.AppendLine();
        }
        sb.AppendLine("## Soldiers");
        foreach (var s in soldiers)
        {
            var a = db.SoldierBranches[s.Id + "_a"]; var bb = db.SoldierBranches[s.Id + "_b"];
            sb.AppendLine($"- **{s.Name}** (`{s.Id}`) HP {s.MaxHp} – {s.Description} Branches: *{a.Name}* ({Elements.Name(a.Element)}) / *{bb.Name}* ({Elements.Name(bb.Element)})");
        }
        sb.AppendLine();
        sb.AppendLine("## Generals");
        foreach (var gid in db.GeneralOrder)
        {
            var g = db.Generals[gid];
            sb.AppendLine($"- **{g.Name} – {g.Title}** ({Elements.Name(g.Element)}, {g.Group}, AI {g.Ai}) – {g.Description} Ultimate: *{g.Ultimate.Name}*. Aura: {g.Aura.Description}" +
                (g.Evolutions.Length == 2 ? $" Evolutions: *{g.Evolutions[0].Name}* / *{g.Evolutions[1].Name}*." : ""));
        }
        sb.AppendLine();
        sb.AppendLine("## Enemies");
        foreach (var f in enemies.GroupBy(e => e.Faction))
        {
            sb.AppendLine($"### {Loc.Faction(f.Key)}");
            foreach (var e in f.OrderBy(e => e.UnlockNight)) sb.AppendLine($"- **{e.Name}** (`{e.Id}`, {e.Behavior}, {e.Move}, night {e.UnlockNight}+) – {e.Description}");
        }
        sb.AppendLine();
        sb.AppendLine("## Bosses");
        foreach (var b in bosses)
        {
            var bd = db.Bosses[b.BossId];
            sb.AppendLine($"- **{b.Name}** – {b.Description} Phases: {string.Join(" → ", bd.Phases.Select(p => p.Name + " [" + string.Join(", ", p.Abilities.Select(x => x.Name)) + "]"))}. Counterplay: {bd.Counterplay}");
        }
        sb.AppendLine();
        sb.AppendLine("## Maps");
        foreach (var m in db.MapOrder.Select(x => db.Maps[x])) sb.AppendLine($"- **{m.Name}** (`{m.Id}`, difficulty {m.Difficulty}, hazard {m.Hazard}) – {m.Description} Protected: {m.ProtectedSides}. Lanes: {string.Join(", ", m.Lanes.Select(l => l.Name))}");
        sb.AppendLine();
        sb.AppendLine("## Royal Decrees");
        foreach (var g in db.DecreeOrder.Select(x => db.Decrees[x]).GroupBy(d => d.Category))
        {
            sb.AppendLine($"### {g.Key} ({g.Count()})");
            foreach (var d in g) sb.AppendLine($"- **{d.Name}** (`{d.Id}`, {d.Rarity}) – {d.Description}");
        }
        if (db.Equipment.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Equipment");
            foreach (var e in db.Equipment.Values) sb.AppendLine($"- [{e.Slot}] **{e.Name}** (`{e.Id}`) – {e.Description}");
        }
        File.WriteAllText(path, sb.ToString());
    }
}
